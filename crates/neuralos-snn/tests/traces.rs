#[test]
fn every_frozen_network_writes_its_trace() {
    let mut replayed = 0;
    macro_rules! replay {
        ($case:ident) => {{
            use frozen::$case as c;
            let case = case_named(&stringify!($case).replace('_', "-"));
            let mut net = FixedNetwork::new(c::NEURONS, c::SYNAPSES, c::DT_US);
            let mut fired = [false; c::N];
            let mut text = format!("{}\n", c::HEADER);
            let mut step = 0u32;
            for &(count, input) in c::DRIVE {
                for _ in 0..count {
                    let time_us = net.time_us();
                    net.step(&input, &mut fired);
                    if !c::SPIKES_ONLY || fired.contains(&true) {
                        row(&mut text, step, time_us, &fired, net.neurons())
                            .expect("a String takes every write");
                    }
                    step += 1;
                }
            }
            assert_eq!(step, c::STEPS, "{}: the drive covers the run", case.name);
            if let Some((n, have, want)) = first_difference(&read(case), &text) {
                panic!(
                    "{}: the frozen network parts from its trace at line {n}:\n  file:  {have}\n  \
                     fixed: {want}",
                    case.name
                );
            }
            replayed += 1;
        }};
    }
    frozen::for_each_frozen!(replay);
    assert!(replayed > 0, "for_each_frozen! reached no module");
}

#[test]
fn every_plasticity_off_case_steps_as_the_std_network() {
    let mut compared = 0;
    macro_rules! compare {
        ($case:ident) => {{
            use frozen::$case as c;
            let case = case_named(&stringify!($case).replace('_', "-"));
            let cases::Run { mut net, drive } = (case.build)();
            let mut fixed = FixedNetwork::<{ c::N }, { c::S }>::try_from(&net)
                .unwrap_or_else(|e| panic!("{}: {e}", case.name));
            let mut fired = [false; c::N];
            for step in 0..case.steps {
                let input = drive(step);
                let spikes = net.step(&input).expect("a built case steps");
                let input: [i16; c::N] = input.try_into().expect("one current per neuron");
                fixed.step(&input, &mut fired);
                let want: Vec<usize> = spikes.iter().map(|s| usize::from(s.neuron_id)).collect();
                let got: Vec<usize> = (0..c::N).filter(|&i| fired[i]).collect();
                assert_eq!(got, want, "{} step {step}: the spikes", case.name);
                for (f, s) in fixed.neurons().iter().zip(net.neurons()) {
                    assert_eq!(
                        f.membrane_potential, s.membrane_potential,
                        "{} step {step}: neuron {}",
                        case.name, s.id
                    );
                }
            }
            compared += 1;
        }};
    }
    frozen::for_each_frozen!(compare);
    let off = CASES
        .iter()
        .filter(|c| !(c.build)().net.plasticity_enabled())
        .count();
    assert_eq!(compared, off, "every plasticity-off case is frozen");
}

#[test]
fn the_network_arm_folds_to_its_pin() {
    use frozen::feedforward_8 as c;
    let [(_, input)] = c::DRIVE else {
        panic!("feedforward-8's drive is one run: constant");
    };
    let mut net = FixedNetwork::new(c::NEURONS, c::SYNAPSES, c::DT_US);
    let mut fired = [false; c::N];
    let (mut spikes, mut first_step, mut checksum) = (0u32, None, 0u32);
    for step in 0..NETWORK_STEPS {
        net.step(input, &mut fired);
        for (id, _) in (0u32..).zip(fired).filter(|&(_, f)| f) {
            spikes += 1;
            first_step.get_or_insert(step);
            checksum = checksum
                .wrapping_mul(31)
                .wrapping_add(step)
                .wrapping_mul(31)
                .wrapping_add(id);
        }
    }
    assert_eq!(
        (spikes, first_step, checksum),
        (NETWORK_SPIKES, Some(NETWORK_FIRST_STEP), NETWORK_CHECKSUM),
        "(spike count, first spike step, fold)"
    );
}
